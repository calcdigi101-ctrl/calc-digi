"""
Regenerate lib/cpi.ts from the BLS CPI flat file (CPI-U, series CUUR0000SA0).

The public API is limited to 25 requests a day and 10 years per request, so
the full history comes from the bulk download instead.
"""
import collections, os, sys, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URL = "https://download.bls.gov/pub/time.series/cu/cu.data.1.AllItems"
MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"]


def load(path=None):
    if path:
        return open(path).read()
    # BLS rejects requests without a descriptive User-Agent.
    req = urllib.request.Request(URL, headers={"User-Agent": "calc-digi CPI updater"})
    return urllib.request.urlopen(req, timeout=60).read().decode()


vals = collections.defaultdict(dict)
for line in load(sys.argv[1] if len(sys.argv) > 1 else None).splitlines()[1:]:
    parts = line.split()
    if len(parts) < 4 or parts[0] != "CUUR0000SA0":
        continue
    year, period, value = int(parts[1]), parts[2], parts[3]
    if period.startswith("M") and period != "M13":
        try:
            vals[year][int(period[1:])] = float(value)
        except ValueError:
            pass  # e.g. October 2025, not collected during the federal shutdown

last_y = max(vals)
last_m = max(vals[last_y])
annual = {y: round(sum(m.values()) / len(m), 3) for y, m in vals.items() if y < last_y and len(m) >= 11}
body = ",\n".join(f"  {y}: {annual[y]}" for y in sorted(annual))
open(os.path.join(ROOT, "lib/cpi.ts"), "w").write(f"""/**
 * US CPI-U (all items, U.S. city average, 1982–84 = 100), series CUUR0000SA0,
 * from the Bureau of Labor Statistics. Annual averages of the monthly index.
 * Generated by scripts/update_cpi.py — rerun it to refresh.
 */
export const CPI_ANNUAL: Record<number, number> = {{
{body},
}};

/** Most recent monthly index value, used for the current year. */
export const CPI_LATEST = {{ year: {last_y}, month: "{MONTHS[last_m - 1]}", value: {vals[last_y][last_m]} }};

export const CPI_FIRST_YEAR = {min(annual)};

/** CPI for a year; the current (incomplete) year uses the latest monthly value. */
export function cpiFor(year: number): number | undefined {{
  if (year === CPI_LATEST.year) return CPI_LATEST.value;
  return CPI_ANNUAL[year];
}}
""")
print("annual", min(annual), "-", max(annual), "| latest", last_y, MONTHS[last_m - 1], vals[last_y][last_m])
